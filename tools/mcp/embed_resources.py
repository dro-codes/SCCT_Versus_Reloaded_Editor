#!/usr/bin/env python3
"""Compile Reloaded.Editor.Mcp/Resources/** into Reloaded.Editor.Mcp/Embedded.gen.h.

The MCP exe serves these files as scct:// resources and prompts
(Resources.cpp, Prompts.cpp), so it needs nothing beside it. The output
defines one static const unsigned char array per file inside the inline
Mcp::EmbeddedFiles() declared by Embedded.h, so every translation unit that
includes it shares one copy of the data.

The header is not committed. The Reloaded.Editor.Mcp build writes it with
embed_resources.ps1, this script's PowerShell twin, before compiling;
tools/test_mcp.sh writes it with this one. The two must write byte-identical
headers and report the same errors: change them together.

    python3 tools/mcp/embed_resources.py                  write Embedded.gen.h if it changed
    python3 tools/mcp/embed_resources.py --output <file>  write another file instead (CI compares it with the build's)
    python3 tools/mcp/embed_resources.py --check          exit 1 if the header is missing or out of date

The output depends only on the files' contents. Paths are relative to
Resources with forward slashes, in byte order. Text files are embedded with
LF line endings, so a CRLF checkout produces the same header, and the header
itself has LF line endings on every OS. JSON files must parse.
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RESOURCES = os.path.join(ROOT, "Reloaded.Editor.Mcp", "Resources")
OUTPUT = os.path.join(ROOT, "Reloaded.Editor.Mcp", "Embedded.gen.h")

MIME = {
    ".md": "text/markdown",
    ".json": "application/json",
    ".png": "image/png",
    ".txt": "text/plain",
    ".csv": "text/csv",
    ".svg": "image/svg+xml",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".bmp": "image/bmp",
    ".tga": "image/x-tga",
}
TEXT = {".md", ".json", ".txt", ".csv", ".svg"}
BYTES_PER_LINE = 24


def collect(resources):
    """[(relative path, mime, bytes)] for every resource file, in byte order of path."""
    files = []
    for folder, dirs, names in os.walk(resources):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        for name in names:
            if name.startswith(".") or name.endswith("~"):
                continue
            full = os.path.join(folder, name)
            relative = os.path.relpath(full, resources).replace(os.sep, "/")
            extension = os.path.splitext(name)[1].lower()
            if extension not in MIME:
                raise SystemExit(f"{relative}: no MIME type for {extension or 'files without an extension'}; add it to MIME in embed_resources.py and embed_resources.ps1.")
            with open(full, "rb") as f:
                data = f.read()
            if extension in TEXT:
                data = data.replace(b"\r\n", b"\n")
                try:
                    text = data.decode("utf-8")
                except UnicodeDecodeError as error:
                    raise SystemExit(f"{relative}: not UTF-8 ({error}).")
                if extension == ".json":
                    try:
                        json.loads(text)
                    except ValueError as error:
                        raise SystemExit(f"{relative}: invalid JSON ({error}).")
            if not relative.isascii() or '"' in relative or "\\" in relative:
                raise SystemExit(f"{relative}: resource paths must be plain ASCII.")
            files.append((relative, MIME[extension], data))
    files.sort(key=lambda item: item[0].encode("utf-8"))
    return files


def render(files):
    total = sum(len(data) for _, _, data in files)
    out = [
        "#pragma once",
        "// Generated by tools/mcp/embed_resources.ps1 (the build) or embed_resources.py from Reloaded.Editor.Mcp/Resources; do not edit.",
        f"// {len(files)} files, {total} bytes. Not committed: the Reloaded.Editor.Mcp build writes it before compiling.",
        '#include "Embedded.h"',
        "",
        "namespace Mcp",
        "{",
        "    inline const std::vector<EmbeddedFile>& EmbeddedFiles()",
        "    {",
    ]
    for index, (path, _, data) in enumerate(files):
        # A trailing zero, not counted in size, keeps empty files legal and text usable as a C string.
        payload = data + b"\0"
        out.append(f"        // {path}")
        out.append(f"        static const unsigned char f{index}[] = {{")
        for start in range(0, len(payload), BYTES_PER_LINE):
            chunk = payload[start:start + BYTES_PER_LINE]
            line = ",".join(f"0x{byte:02x}" for byte in chunk)
            out.append("            " + line + ("," if start + BYTES_PER_LINE < len(payload) else ""))
        out.append("        };")
    out.append("        static const std::vector<EmbeddedFile> files{")
    for index, (path, mime, data) in enumerate(files):
        out.append(f'            {{"{path}", "{mime}", f{index}, {len(data)}}},')
    out.append("        };")
    out.append("        return files;")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the output is missing or out of date, writing nothing")
    parser.add_argument("--resources", default=RESOURCES, help="the Resources folder (default: the repository's)")
    parser.add_argument("--output", default=OUTPUT, help="the header to write (default: Reloaded.Editor.Mcp/Embedded.gen.h)")
    args = parser.parse_args()

    files = collect(args.resources)
    # Bytes, so a header with CRLF line endings (an old checkout's) is rewritten.
    header = render(files).encode("utf-8")
    try:
        with open(args.output, "rb") as f:
            current = f.read()
    except FileNotFoundError:
        current = None

    if args.check:
        if current != header:
            print(f"{os.path.relpath(args.output, ROOT)} is out of date: rebuild Reloaded.Editor.Mcp or run python3 tools/mcp/embed_resources.py.", file=sys.stderr)
            return 1
        print(f"{os.path.relpath(args.output, ROOT)} is up to date ({len(files)} files).")
        return 0
    if current == header:
        print(f"{os.path.relpath(args.output, ROOT)} unchanged ({len(files)} files).")
        return 0
    # Binary, so the header has LF line endings on every OS, as the PowerShell twin writes it.
    with open(args.output, "wb") as f:
        f.write(header)
    print(f"Wrote {os.path.relpath(args.output, ROOT)}: {len(files)} files, {sum(len(d) for _, _, d in files)} bytes.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
